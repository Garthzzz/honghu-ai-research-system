def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _ev(ref: str) -> str:
    return f"source_ref:{ref}"


def _cite(ref: str) -> str:
    return f"^src:{_ev(ref)}"


def _link_company_mentions(body: str) -> str:
    blocks = re.split(r"(\n\s*\n)", body)
    linked: list[str] = []
    for block in blocks:
        stripped = block.lstrip()
        if (
            not stripped
            or stripped.startswith("#")
            or stripped.startswith("|")
            or stripped.startswith("```")
            or f"]({COMPANY_ROUTE})" in block
        ):
            linked.append(block)
            continue
        linked.append(
            re.sub(
                re.escape(COMPANY_NAME),
                f"[{COMPANY_NAME}]({COMPANY_ROUTE})",
                block,
                count=1,
            )
        )
    return "".join(linked)


def _section(
    key: str, title: str, body: str, refs: list[str], order: int
) -> dict[str, Any]:
    missing_headings = [
        heading for heading in PUBLIC_SECTION_HEADINGS if heading not in body
    ]
    if missing_headings:
        raise ValueError(
            f"{key} 缺少公开章节结构小标题: {missing_headings}"
        )
    inline_refs = [ref for ref in SOURCE_BY_REF if _cite(ref) in body]
    return {
        "section_key": key,
        "section_title": title,
        "title": title,
        "body_markdown": _link_company_mentions(body.strip()),
        "evidence_ref_uri_list": [
            _ev(ref) for ref in (inline_refs or refs)
        ],
        "support_status": "supported",
        "review_status": "approved",
        "sort_order": order,
    }


