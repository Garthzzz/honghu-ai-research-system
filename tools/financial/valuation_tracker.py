def load_seed(path: str | Path) -> dict[str, Any]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if payload.get("schema_version") != "honghu.valuation_tracker.workbook_seed.v1":
        raise ValuationTrackerError("unsupported valuation tracker seed")
    return payload
