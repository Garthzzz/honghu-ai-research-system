def bibliography(source_ids: dict[str, int], keys: Iterable[str]) -> str:
    by_key = {s.key: s for s in SOURCES}
    seen: set[str] = set()
    lines = ["\n## 来源索引\n"]
    for key in keys:
        if key in seen or key not in source_ids or key not in by_key:
            continue
        seen.add(key)
        s = by_key[key]
        stale = "；2024或更早，仅作历史回测" if s.publish_date and s.publish_date[:4].isdigit() and int(s.publish_date[:4]) <= 2024 else ""
        lines.append(f"- ^src:{source_ids[key]} {s.publisher}《{s.title}》（{s.publish_date}，T{s.quality_tier}{stale}）")
    return "\n".join(lines) + "\n"


def _fmt(v: Any, digits: int = 1) -> str:
    if v is None:
        return "客观不可得"
    if isinstance(v, (int, float)):
        return f"{v:,.{digits}f}"
    return str(v)


