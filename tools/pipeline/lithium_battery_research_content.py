def _consensus_rows(name: str) -> list[dict[str, Any]]:
    run_by_id = {int(item["id"]): item for item in RECON["modelRuns"]}
    return [
        row
        for row in RECON["reconciliations"]
        if row["benchmark_type"] == "consensus"
        and row["metric_name"] == "归母净利润"
        and name in run_by_id[int(row["model_run_id"])]["model_name"]
    ]


def _consensus_sentence(name: str) -> str:
    rows = sorted(_consensus_rows(name), key=lambda row: row["period"])
    if not rows:
        return (
            "最近两个季度内没有足以形成同口径FY1—FY3模型的活跃卖方预测，"
            "因此不伪造市场中位数；公司页只显示独立模型和当前市场反向诊断。"
        )
    source = rows[0]["decomposition"]
    values = "、".join(
        f"{row['period']}年{_fmt(row['benchmark_value'])}亿元"
        for row in rows
    )
    diffs = "、".join(
        f"{row['period']}年{row['difference_pct']*100:+.2f}%"
        for row in rows
    )
    return (
        f"外部基准采用{source.get('publisher', '外部基准')}于"
        f"{source.get('publication_date', '研究截止日前')}形成的同口径预测："
        f"{values}；独立模型相对它的差异依次为{diffs}。"
    )


def _segment_assumption_table(name: str) -> str:
    item = _model(name)
    years = (2026, 2027, 2028)
    lines = [
        "| 业务 | 2026输入 | 2027输入 | 2028输入 | 毛利率路径 | 判断依据 |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for segment in item["inputs"]["segments"]:
        if segment["kind"] in {"battery_gwh", "vehicle_million_units"}:
            unit = "GWh" if segment["kind"] == "battery_gwh" else "百万辆"
            input_cells = [
                f"{segment['volume'][str(year)] if str(year) in segment['volume'] else segment['volume'][year]:g}{unit}"
                + " × "
                + (
                    f"{segment['asp'][str(year)] if str(year) in segment['asp'] else segment['asp'][year]:.2f}元/Wh"
                    if segment["kind"] == "battery_gwh"
                    else f"{segment['asp'][str(year)] if str(year) in segment['asp'] else segment['asp'][year]:,.0f}元/辆"
                )
                for year in years
            ]
        else:
            input_cells = [
                f"{segment['revenue'][str(year)] if str(year) in segment['revenue'] else segment['revenue'][year]:,.2f}亿元"
                for year in years
            ]
        margins = [
            segment["grossMargin"][str(year)]
            if str(year) in segment["grossMargin"]
            else segment["grossMargin"][year]
            for year in years
        ]
        lines.append(
            f"| {segment['name']} | {input_cells[0]} | {input_cells[1]} | "
            f"{input_cells[2]} | {margins[0]*100:.2f}%→{margins[1]*100:.2f}%"
            f"→{margins[2]*100:.2f}% | {segment['note']} |"
        )
    return "\n".join(lines)


