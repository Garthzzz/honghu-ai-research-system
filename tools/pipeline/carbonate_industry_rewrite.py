def _balance_table(model: dict[str, Any]) -> str:
    lines = [
        "| 年份 | 国内产量 | 进口 | 出口 | 表观供给 | 下游需求 | 产品余额 | 余额/需求 | 数据性质 |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in model["rows"]:
        lines.append(
            f"| {row['year']} | {float(row['domestic_output_mt']) * 100:.2f} | "
            f"{float(row['imports_mt']) * 100:.2f} | "
            f"{float(row['exports_mt']) * 100:.2f} | "
            f"{float(row['available_supply_mt']) * 100:.2f} | "
            f"{float(row['demand_mt']) * 100:.2f} | "
            f"{float(row['balance_mt']) * 100:+.2f} | "
            f"{float(row['balance_ratio_pct']):+.2f}% | {row['status']} |"
        )
    return "\n".join(lines)


def _h1_route_table(model: dict[str, Any]) -> str:
    observed = model["observed_2026_h1"]
    total = float(observed["smm_domestic_output_mt"])
    route_rows = list(observed["route_output_mt"].items())
    covered = sum(float(value) for _, value in route_rows)
    lines = [
        "| 2026H1生产路线 | 产量（万吨碳酸锂） | 占SMM总产量 | 供给特征 | 主要约束 |",
        "|---|---:|---:|---|---|",
    ]
    notes = {
        "锂辉石": ("最大单一路线，进口精矿与国内矿并存", "精矿价格、品位、长协和加工价差"),
        "锂云母": ("中国特有的边际弹性路线", "品位、能耗、尾渣处置、采矿和环保"),
        "盐湖": ("现金成本较低但爬坡通常较慢", "提锂工艺、季节、杂质和稳定品质"),
        "回收": ("跟随废料可得性和金属价格变化", "黑粉来源、回收率、价差和合规"),
    }
    for name, value in route_rows:
        feature, constraint = notes[name]
        lines.append(
            f"| {name} | {float(value) * 100:.2f} | "
            f"{float(value) / total * 100:.2f}% | {feature} | {constraint} |"
        )
    residual = max(0.0, total - covered)
    lines.append(
        f"| 其他及统计差 | {residual * 100:.2f} | "
        f"{residual / total * 100:.2f}% | 样本与分类口径差 | 不作工艺利润推断 |"
    )
    return "\n".join(lines)


