def _official_balance_table(model: dict[str, Any]) -> str:
    lines = [
        "| 年份 | 可用供给（百万吨LCE） | 需求（百万吨LCE） | 余额（万吨LCE） | 余额/需求 | 判断 |",
        "|---:|---:|---:|---:|---:|---|",
    ]
    for row in model["base_rows"]:
        supply = float(row["available_supply_mt_lce"])
        demand = float(row["demand_mt_lce"])
        balance = float(row["balance_mt_lce"])
        ratio = balance / demand * 100
        if ratio > 5:
            conclusion = "总量仍有缓冲"
        elif ratio > 0:
            conclusion = "接近平衡，易受项目扰动"
        else:
            conclusion = "基准出现小幅缺口"
        lines.append(
            f"| {row['year']} | {supply:.3f} | {demand:.3f} | "
            f"{balance * 100:+.1f} | {ratio:+.2f}% | {conclusion} |"
        )
    return "\n".join(lines)


