def source_index(source_ids: dict[str, int], refs: Iterable[str]) -> str:
    by_ref = {item["source_ref"]: item for item in SOURCE_SPECS}
    lines = ["## 来源索引", ""]
    for ref in dict.fromkeys(refs):
        if ref not in source_ids or ref not in by_ref:
            continue
        item = by_ref[ref]
        lines.append(
            f"- ^src:{source_ids[ref]} {item['publisher']}，"
            f"《{item['title']}》，{item.get('publish_date') or '日期未标注'}。"
        )
    return "\n".join(lines) + "\n"


